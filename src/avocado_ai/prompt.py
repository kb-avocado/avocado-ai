def type_criteria(row: dict[str, Any]) -> str:
    """DB 값을 우선 사용하고, 없으면 폴백 기준을 반환한다."""
    from_db = (row.get("type_description") or "").strip()

    if from_db:
        return from_db

    return _TYPE_CRITERIA_FALLBACK.get(
        row.get("type_code"),
        "기본값",
    )


def suggestion_direction(row: dict[str, Any]) -> str:
    """유형별 큰 방향을 반환한다.

    방향은 조언 내용을 직접 결정하지 않고,
    실제 데이터를 해석할 때 참고하는 역할만 한다.
    """
    code = row.get("type_code")

    if code != "ROLLER_COASTER":
        return TYPE_ADVICE_DIRECTION.get(
            code,
            TYPE_ADVICE_DIRECTION["SPROUT"],
        )

    last = row.get("last_month_spent")

    if not last:
        return _ROLLER_COASTER_NO_BASE

    total = row.get("total_spent") or 0

    if total > last:
        return _ROLLER_COASTER_UP

    return _ROLLER_COASTER_DOWN


def _won(amount: Any) -> str:
    """금액을 한국 원화 표기로 변환한다."""
    return f"{int(amount or 0):,}원"


def _top_spots_lines(
    row: dict[str, Any],
    cfg: AdviceConfig,
) -> list[str]:
    """상위 3개 소비처 정보를 생성한다."""

    spots = (row.get("top_spots") or [])[:3]

    if not spots:
        return ["- 많이 쓴 곳: 기록 없음"]

    lines = ["- 많이 쓴 곳 (상위 3):"]

    for i, spot in enumerate(spots, start=1):
        share = spot.get("percentage")
        share_text = f"전체의 {share}%" if share is not None else "비율 미상"

        amount = spot.get("amount")
        amount_text = f", {_won(amount)}" if amount is not None else ""

        if cfg.include_merchant_names:
            label = (
                spot.get("category")
                or spot.get("merchant_name")
                or "기타"
            )
        else:
            label = f"{i}번째로 많이 간 곳"

        lines.append(
            f"    {i}위 {label} — {share_text}{amount_text}"
        )

    return lines


def _roller_coaster_lines(row: dict[str, Any]) -> list[str]:
    """ROLLER_COASTER인 경우 전월 소비 정보를 추가한다."""

    if row.get("type_code") != "ROLLER_COASTER":
        return []

    last = row.get("last_month_spent")

    if not last:
        return [
            "",
            "[전월 대비]",
            "- 비교할 지난달 기록이 없다 (이번 달이 첫 기록).",
            "- 늘었다/줄었다 같은 증감 표현을 사용하지 마라.",
        ]

    total = int(row.get("total_spent") or 0)
    direction = "늘었다" if total > last else "줄었다"

    return [
        "",
        "[전월 대비]",
        f"- 지난달 {_won(last)} → 이번 달 {_won(total)} ({direction})",
        f"- 증감 방향은 '{direction}'로 고정한다.",
    ]


def build_user_prompt(
    row: dict[str, Any],
    cfg: AdviceConfig,
) -> str:
    """LLM에 전달할 소비 리포트 데이터를 생성한다."""

    code = row.get("type_code") or "SPROUT"

    lines = [
        f"[{row['report_year']}년 {row['report_month']}월 소비 리포트]",
        "",
        "[이번 달 기록]",
        f"- 한 달간 쓴 돈 총액: {_won(row.get('total_spent'))}",
        f"- 결제 건수: {int(row.get('transaction_count') or 0)}건",
        f"- 저금한 돈: {_won(row.get('total_saved'))}",
        f"- 받은 용돈: {_won(row.get('allowance_received'))}",
        f"- 저축률: {row.get('saving_rate')}%",
        "",
        *_top_spots_lines(row, cfg),
        *_roller_coaster_lines(row),
        "",
        "[소비 유형 참고]",
        f"- 유형: {row.get('type_name')} ({code})",
        f"- 유형 기준: {type_criteria(row)}",
        "",
        "[이번 조언에서 참고할 큰 방향]",
        f"- {suggestion_direction(row)}",
        "",
        "[중요]",
        "- 큰 방향은 조언의 내용을 그대로 결정하지 않는다.",
        "- 실제 이번 달 데이터를 가장 우선한다.",
        "- 데이터에서 가장 의미 있는 특징 하나를 선택한다.",
        "- 그 특징과 연결되는 구체적인 행동 하나를 제안한다.",
        "- 유형명이나 유형 기준을 조언에 직접 설명하지 않는다.",
        "",
        "childAdvice와 parentAdvice를 각각 정확히 두 문장으로 작성하고,",
        "JSON 하나로만 답하라.",
    ]

    return "\n".join(lines)